import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version",
};

serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const { messages, action } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY is not configured");

    const systemPrompts: Record<string, string> = {
      write: `Eres un asistente experto en redacción de documentos profesionales. 
Genera documentos bien estructurados con formato Markdown. 
Usa encabezados (#, ##, ###), listas, negritas y otros elementos de formato.
Responde siempre en español salvo que se indique lo contrario.
Si te piden crear un documento, genera el contenido completo y profesional.`,
      edit: `Eres un editor profesional de documentos. El usuario te proporcionará un documento existente y te pedirá modificaciones.
Devuelve el documento completo modificado en formato Markdown.
Mantén el formato y estructura existente salvo que se indique lo contrario.`,
      improve: `Eres un editor profesional. Mejora el documento proporcionado: corrige gramática, mejora redacción, 
añade estructura si falta, y hazlo más profesional. Devuelve el documento completo mejorado en Markdown.`,
      summarize: `Eres un asistente de resumen. Resume el documento proporcionado de forma clara y concisa.
Mantén los puntos clave y genera un resumen en formato Markdown.`,
    };

    const systemContent = systemPrompts[action] || systemPrompts.write;

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-2.5-flash",
        messages: [
          { role: "system", content: systemContent },
          ...messages,
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Límite de solicitudes excedido. Inténtalo de nuevo en unos momentos." }), {
          status: 429,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "Se requiere crédito adicional para usar la IA." }), {
          status: 402,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const t = await response.text();
      console.error("AI gateway error:", response.status, t);
      return new Response(JSON.stringify({ error: "Error del servicio de IA" }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("document-ai error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Error desconocido" }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
